-- ============================================================================
-- 01 · Esquema completo en PostgreSQL
-- ============================================================================
--
-- El estado final del esquema que en MariaDB construian 55 migraciones y los
-- guiones de `database/sql/multi-tenant/` (archivados en
-- `database/historico-mariadb/`). Tablas, columnas, claves, unicos, indices,
-- CHECK, columnas generadas y el trigger de cupo, con los MISMOS nombres: el
-- codigo reconoce algunos errores por el nombre del indice que salto
-- (`App\Support\ErrorDeBaseDeDatos`).
--
-- Idempotente: se puede correr dos veces seguidas, o de nuevo tras un fallo a
-- medias, y termina en el mismo estado. Todo es `IF NOT EXISTS` o `OR
-- REPLACE`. PostgreSQL 18 o superior (ver el cotejo). Con el cliente:
--   psql -h ... -p ... -U ... -d nombre_de_la_base -f este_archivo.sql
--
-- Las traducciones que no son evidentes:
--
-- * COTEJO. MariaDB comparaba con `utf8mb4_unicode_ci`, que no distingue
--   mayusculas NI tildes: `Ana` entra como `ana`, el buscador encuentra
--   «musica» en «Música» y un departamento «musica» choca con «Música». En
--   PostgreSQL eso es el cotejo ICU no determinista `insensible`, puesto en
--   cada columna de texto. Hace falta la 18: es la primera que admite LIKE con
--   un cotejo no determinista. Lo que NO replica: MariaDB ignoraba los
--   espacios al final al comparar (`'a' = 'a '`); aqui no.
--   Las expresiones regulares no admiten este cotejo, por eso el CHECK del
--   color va con `COLLATE "C"`.
--
-- * SIN SIGNO. PostgreSQL no tiene enteros sin signo. Las claves pasan a
--   `bigint` (nunca son negativas); las columnas de datos pasan al entero
--   siguiente con un CHECK que conserva el rango de antes, salvo donde ya
--   habia uno mas estrecho.
--
-- * BOOLEANOS. `tinyint(1)` pasa a `boolean`.
--
-- * COLUMNAS GENERADAS. MariaDB las tenia VIRTUAL; aqui son STORED (la
--   unica forma que admite un indice unico). Mismo nombre, misma regla.
--
-- * `restablecimientos_clave.created_at` llevaba `ON UPDATE
--   CURRENT_TIMESTAMP`, que PostgreSQL no tiene: lo hace un trigger.
--
-- * FECHAS. `datetime` y `timestamp` pasan a `timestamp(0)` sin zona: la
--   aplicacion guarda la hora local y asi la lee.
-- ============================================================================

