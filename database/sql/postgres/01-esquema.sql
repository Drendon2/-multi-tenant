-- El cupo de promotoria. Era el trigger de MariaDB con `SIGNAL SQLSTATE
-- '45000'`: se conserva el MISMO estado y el mismo mensaje, que es lo que
-- reconoce `ErrorDeBaseDeDatos::esCupoAgotado()`.
--
-- El `FOR UPDATE` sobre la fila del cupo pone en fila a dos inscripciones que
-- compiten por el ultimo sitio; en READ COMMITTED cada consulta de la funcion
-- toma su propia foto, asi que el COUNT de despues de la espera ya ve la
-- matricula de la otra.
CREATE OR REPLACE FUNCTION cupo_promotoria_disponible() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
  v_maximo      bigint;
  v_ocupados    bigint;
  v_promotoria  varchar(60);
  v_periodo     varchar(20);
BEGIN
  -- Una matricula retirada no ocupa sitio: nada que comprobar.
  IF NEW.estado = 'retirada' THEN
    RETURN NEW;
  END IF;

  -- Seguir ocupando el mismo sitio no pide uno nuevo.
  IF TG_OP = 'UPDATE' THEN
    IF OLD.estado <> 'retirada'
       AND OLD.promotoria_id = NEW.promotoria_id
       AND OLD.periodo_id = NEW.periodo_id THEN
      RETURN NEW;
    END IF;
  END IF;

  SELECT cupo_maximo INTO v_maximo
    FROM cupos_promotoria
   WHERE promotoria_id = NEW.promotoria_id
     AND periodo_id = NEW.periodo_id
     FOR UPDATE;

  -- Sin cupo definido para ese periodo, no hay tope.
  IF v_maximo IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT COUNT(*) INTO v_ocupados
    FROM matriculas
   WHERE promotoria_id = NEW.promotoria_id
     AND periodo_id = NEW.periodo_id
     AND estado <> 'retirada'
     AND (TG_OP = 'INSERT' OR id IS DISTINCT FROM NEW.id);

  IF v_ocupados >= v_maximo THEN
    SELECT nombre INTO v_promotoria FROM promotorias WHERE id = NEW.promotoria_id;
    SELECT nombre INTO v_periodo FROM periodos WHERE id = NEW.periodo_id;
    RAISE EXCEPTION USING
      ERRCODE = '45000',
      MESSAGE = v_promotoria || ' no tiene cupos disponibles para ' || v_periodo || ': '
                || v_ocupados || ' de ' || v_maximo
                || ' ocupados, contando las solicitudes pendientes.';
  END IF;

  RETURN NEW;
END
$$;

CREATE OR REPLACE TRIGGER cupo_promotoria_disponible_insert
  BEFORE INSERT ON matriculas
  FOR EACH ROW EXECUTE FUNCTION cupo_promotoria_disponible();

CREATE OR REPLACE TRIGGER cupo_promotoria_disponible_update
  BEFORE UPDATE ON matriculas
  FOR EACH ROW EXECUTE FUNCTION cupo_promotoria_disponible();

