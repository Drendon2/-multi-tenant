-- El `ON UPDATE CURRENT_TIMESTAMP` de MariaDB: si la fila cambia y nadie toca
-- `created_at`, se pone la hora de ahora. Si la escritura la pone a mano, se
-- respeta, igual que alli.
CREATE OR REPLACE FUNCTION restablecimiento_al_dia() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.created_at IS NOT DISTINCT FROM OLD.created_at
     AND (NEW.user_id, NEW.institucion_id, NEW.token)
         IS DISTINCT FROM (OLD.user_id, OLD.institucion_id, OLD.token) THEN
    NEW.created_at := LOCALTIMESTAMP(0);
  END IF;
  RETURN NEW;
END
$$;

CREATE OR REPLACE TRIGGER restablecimiento_al_dia
  BEFORE UPDATE ON restablecimientos_clave
  FOR EACH ROW EXECUTE FUNCTION restablecimiento_al_dia();

